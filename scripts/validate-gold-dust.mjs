import assert from "node:assert/strict";
import * as THREE from "three";
import { createGoldDust } from "../src/gold-dust.js";

const options = { center: new THREE.Vector3(10, 20, 30), radii: new THREE.Vector3(500, 300, 400), pixelRatio: 3 };
const dust = createGoldDust(options);
const { points } = dust;
const uniforms = points.material.uniforms;
assert.equal(points.geometry.getAttribute("position").count, 2600);
assert.equal(points.geometry.getAttribute("aSeed").count, 2600);
assert.ok([...points.geometry.getAttribute("aSeed").array].every((value) => value >= 0 && value < 1));
assert.deepEqual(points.position, options.center);
assert.equal(uniforms.uPixelRatio.value, 2);
assert.equal(points.material.depthWrite, false);
const hitResults = [];
points.raycast(new THREE.Raycaster(), hitResults);
assert.deepEqual(hitResults, [], "金色粒子不可截获人物或关系点击");
dust.update(0.04);
assert.equal(uniforms.uTime.value, 0.04);
for (let i = 0; i < 100; i++) dust.update(0.02, { focused: true });
assert.ok(uniforms.uOpacity.value < 0.1, "聚焦时粒子必须减弱");
for (let i = 0; i < 100; i++) dust.update(0.02);
assert.ok(uniforms.uOpacity.value > 0.33);
const time = uniforms.uTime.value;
dust.update(0.05, { reducedMotion: true });
assert.equal(uniforms.uTime.value, time);
dust.update(0.05, { hidden: true });
assert.equal(uniforms.uTime.value, time);
dust.update(0.05, { active: false });
assert.equal(points.visible, false);
assert.equal(uniforms.uTime.value, time);
dust.update(100);
assert.equal(points.visible, true);
assert.ok(uniforms.uTime.value - time <= 0.051, "重新进入不得出现跳帧流泻");
const mobile = createGoldDust({ ...options, compact: true });
assert.equal(mobile.points.geometry.getAttribute("position").count, 1200);
const again = createGoldDust(options);
assert.deepEqual(again.points.geometry.getAttribute("aSeed").array, points.geometry.getAttribute("aSeed").array);
for (const field of [dust, mobile, again]) field.dispose();
console.log("金色粒子检查通过：轻量单层、移动端减量、非交互、聚焦减弱、减少动态效果与后台暂停。");
